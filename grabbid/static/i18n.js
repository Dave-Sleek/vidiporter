  function populateLangSelect(selectEl) {
    if (!selectEl) return;
    const fragment = document.createDocumentFragment();
    SUPPORTED_LANGUAGES.forEach((item) => {
      const opt = document.createElement("option");
      opt.value = item.code;
      opt.textContent = `${item.flag} ${item.label}`;
      fragment.appendChild(opt);
    });
    selectEl.innerHTML = "";
    selectEl.appendChild(fragment);
  }

  function getSavedLanguage() {
    try {
      const saved = localStorage.getItem(LANG_STORAGE_KEY);
      if (saved && TRANSLATIONS[saved]) {
        return saved;
      }
    } catch (_) {
      // Ignore storage errors
    }
    const rawBrowserLang = (navigator.language || "en").slice(0, 2).toLowerCase();
    const browserLang = rawBrowserLang === "in" ? "id" : rawBrowserLang;
    return TRANSLATIONS[browserLang] ? browserLang : "en";
  }

  let currentLang = getSavedLanguage();

  function t(key) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  function applyTranslations(lang) {
    const normalized = TRANSLATIONS[lang] ? lang : "en";
    currentLang = normalized;
    document.documentElement.setAttribute("lang", normalized);
    document.documentElement.setAttribute("dir", normalized === "ar" ? "rtl" : "ltr");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) {
        el.textContent = t(key);
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) {
        el.setAttribute("placeholder", t(key));
      }
    });

    const langSelect = document.getElementById("langSelect");
    if (langSelect && langSelect.value !== normalized) {
      langSelect.value = normalized;
    }

    const themeLabel = document.getElementById("themeLabel");
    if (themeLabel) {
      const currentTheme = document.documentElement.getAttribute("data-theme") || "dark";
      themeLabel.textContent = currentTheme === "light" ? t("theme.dark") : t("theme.light");
    }

    try {
      localStorage.setItem(LANG_STORAGE_KEY, normalized);
    } catch (_) {
      // Ignore storage errors
    }

    document.dispatchEvent(new CustomEvent("vidiporter:langchange", { detail: { lang: normalized } }));
  }

  function initI18n() {
    const langSelect = document.getElementById("langSelect");
    if (langSelect) {
      populateLangSelect(langSelect);
      langSelect.value = currentLang;
      langSelect.addEventListener("change", (event) => {
        applyTranslations(event.target.value);
      });
    }
    applyTranslations(currentLang);
  }

  window.VidiporterI18n = {
    t,
    applyTranslations,
    getLanguage: () => currentLang,
    languages: SUPPORTED_LANGUAGES,
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initI18n);
  } else {
    initI18n();
  }
